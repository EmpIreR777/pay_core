"""Фоновые задачи шлюза (T-4.4).

Каждая задача здесь — тонкая обёртка над слоем ``db``: она умеет получить
зависимости, позвать работу и сообщить результат. Бизнес-правил в задачах нет,
они живут там же, где и у остального кода, — в адаптерах; иначе правило
уборки и правило её запуска разошлись бы при первой же правке одного из них.
"""

import logging
from datetime import UTC, datetime
from typing import Final

from src.db.idempotency_cleanup import delete_expired_idempotency_keys
from src.db.session_make import async_session_maker
from src.tasks.broker import broker

logger = logging.getLogger(__name__)

#: Имя расписания уборки: в начале каждого часа.
#:
#: Час выбран потому, что просроченная запись уже никому ничего не должна: она
#: не выдаётся на повтор и место занимает только. Проверять её чаще — значит
#: платить за пустые проходы по таблице чаще, а пропустить нельзя ничего:
#: запись, протухшая час назад, не станет нужнее через минуту.
IDEMPOTENCY_CLEANUP_CRON: Final[str] = '0 * * * *'


@broker.task(schedule=[{'cron': IDEMPOTENCY_CLEANUP_CRON}])
async def cleanup_idempotency_keys() -> int:
    """Убрать просроченные ключи идемпотентности.

    :returns: сколько записей удалено — попадёт в лог, чтобы молчание задачи
        было видно: ноль на протяжении часов означает сбой, а не «нечего
        было убирать».

    Отсечка — ``datetime.now(UTC)`` на момент запуска, и она же передаётся в
    уборку: за проход время не двигается, поэтому проход конечен и повторяем.

    Расписание задано ярлыком ``schedule`` при объявлении, а не отдельным
    списком в шедулере: ярлык едет вместе с задачей, и зарегистрировать её в
    расписании невозможно, забыв про это, — задача просто не найдёт своего
    расписания и молча не запустится.
    """
    deleted = await delete_expired_idempotency_keys(async_session_maker, datetime.now(UTC))
    logger.info('Уборка ключей идемпотентности удалила %d просроченных записей', deleted)
    return deleted
