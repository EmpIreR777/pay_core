"""Базовые доменные исключения.

Правило кодекса (AGENT.md, раздел 4): любое доменное исключение наследуется
от ``DomainError``. Дополнительное наследование от ``ValueError`` у ошибок
некорректного входного значения сделано намеренно — это позволяет обрабатывать
их обычным ``except ValueError`` на границах слоёв, не теряя доменной
семантики внутри ядра.

Ошибки бизнес-правил (``InsufficientFunds``, ``AccountBlocked``,
``InvalidTransition``, ``DuplicateOperation``, ``PaymentProviderError``)
наследуются непосредственно от ``DomainError`` и сигнализируют об отказах
бизнес-логики и внешних интеграций домена.
"""


class DomainError(Exception):
    """Базовая точка иерархии исключений доменного слоя.

    Ловится в application/ и инфраструктуре для маппинга на транспортный
    протокол (gRPC-код, HTTP-статус). Наружу наружу утекать не должен.
    """


class InvalidValueError(DomainError, ValueError):
    """Некорректное значение, переданное в Value Object.

    Наследует ``ValueError``, потому что по смыслу это подкласс ошибок
    разбора/валидации значения, а не логики агрегата.
    """


class InvalidCurrencyError(InvalidValueError):
    """Код валюты не соответствует формату ISO 4217 (три ASCII-буквы)."""


class CurrencyMismatchError(DomainError, ValueError):
    """Попытка сложить, вычесть или сравнить деньги в разных валютах.

    Молча конвертировать нельзя: курс — внешняя политика, а не доменное
    свойство денег. Сначала нужно явно получить новую сумму нужной валюты.
    """


class InvalidAmountError(InvalidValueError):
    """Сумма имеет неподдерживаемый тип, значение или величину."""


class NegativeAmountError(InvalidAmountError):
    """Сумма отрицательна.

    ``Money`` моделирует ненаправленную величину: знак операции задаётся
    доменным методом (пополнение/списание), а не знаком внутри суммы.
    """


class InvalidIdentifierError(InvalidValueError):
    """Идентификатор сущности не является корректным UUID."""


class InsufficientFunds(DomainError):
    """На счёте не хватает денег для операции списания.

    Не подменяется ``ValueError`` в отличие от ошибок разбора входа: это не
    «плохое значение», а отказ бизнес-правила, и прикладной слой обязан отличить
    одно от другого (например, чтобы не каждое такое отклонение оборачивать в
    ошибку валидации запроса).
    """


class AccountBlocked(DomainError):
    """Операция с балансом запрошена у заблокированного счёта.

    Блокировка — это «заморозка» счёта целиком: нельзя ни пополнить, ни
    списать, но можно разблокировать.
    """


class InvalidTransition(DomainError):
    """Попытка совершить недопустимый переход статуса сущности (например, Payment).

    Статус-машина защищает бизнес-инварианты жизненного цикла платежа:
    нельзя перейти из PENDING сразу в SETTLED без PROCESSING, или изменить
    терминальный статус (SETTLED, FAILED, CANCELLED).
    """


class EntityNotFoundError(DomainError):
    """Запрошенная сущность не найдена в хранилище.

    Отличается от ``InvalidIdentifierError`` тем, что идентификатор корректен —
    просто записи с ним нет. Это не «плохой вход», а ответ хранилища, поэтому
    ошибка не наследует ``ValueError``: вызывающий различает «исправь запрос»
    (ошибка значения) и «такого объекта нет» (404 на транспорте).
    """


class DuplicateOperation(DomainError):
    """Попытка повторного выполнения уже обработанной или выполняемой операции.

    Используется при нарушении семантики идемпотентности: например, при повторном
    запросе на создание платежа с тем же idempotency key или параллельной обработке.
    """


class PaymentProviderError(DomainError):
    """Ошибка взаимодействия с внешним платёжным провайдером.

    Сигнализирует о сбое на стороне шлюза эквайринга (отказ провайдера, сетевой сбой,
    некорректный ответ или ошибка протокола).
    """
