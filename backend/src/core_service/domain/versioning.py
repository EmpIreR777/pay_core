"""Константы оптимистичной блокировки — один источник для всех агрегатов (T-2.3).

Версия записи — сквозной факт схемы: её хранит SQLAlchemy ``version_id_col`` и
увеличивает каждое успешное изменение состояния агрегата. Держать это число
в двух модулях (счёт и платёж) значит однажды поменять в одном и получить
расхождение, которое проявится уже на ``UPDATE`` в проде. Поэтому число одно,
а агрегаты импортируют его отсюда.
"""

from typing import Final

#: Версия только что созданной записи.
INITIAL_VERSION: Final = 1

#: Ниже этой версии запись не существует: нулевая версия означала бы, что запись
#: «создаётся» прямо сейчас, и проверка версии в UPDATE потеряла бы смысл.
MIN_VERSION: Final = 1
