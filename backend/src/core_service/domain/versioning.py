"""Константы оптимистичной блокировки — один источник для всех агрегатов (T-2.3).

Версия записи — сквозной факт схемы, но **счётчик принадлежит домену**: агрегат
увеличивает ``version`` на единицу за каждое реальное изменение состояния
(``deposit``/``withdraw``/``block``, переход статуса платежа). Хранилище лишь
записывает это число и сверяет его в условии ``UPDATE`` (T-3.6). ``SQLAlchemy
version_id_col`` не используется намеренно: он считает **записи**, а не изменения, и
при нескольких изменениях до одного сохранения разошёлся бы с агрегатом.

Отсюда следствие, ради которого и заведено отдельное поле ``persisted_version``:
между чтением и сохранением версия вырастает не обязательно на единицу, а на число
изменений (``process`` + ``settle`` — это ``+2``). Поэтому ожидаемая версия хранится
рядом с текущей, а не вычисляется как ``version - 1``.

Держать это число в двух модулях (счёт и платёж) значит однажды поменять в одном и
получить расхождение, которое проявится уже на ``UPDATE`` в проде. Поэтому число
одно, а агрегаты импортируют его отсюда.
"""

from typing import Final

#: Версия только что созданной записи.
INITIAL_VERSION: Final = 1

#: Ниже этой версии запись не существует: нулевая версия означала бы, что запись
#: «создаётся» прямо сейчас, и проверка версии в UPDATE потеряла бы смысл.
MIN_VERSION: Final = 1
