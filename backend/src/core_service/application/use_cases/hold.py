"""Возврат зарезервированных под платёж средств: единственное место этого правила.

Правило «отдать холд обратно на счёт плательщика» одинаково для сценариев, которые
закрывают платёж, не проведя его: ответа провайдера (T-2.4, T-2.5, T-2.7) и отмены
(T-2.6). У каждого была бы своя копия — и одна из них рано или поздно забудет про
возврат денег, а клиент потеряет сумму. Поэтому правило живёт здесь, а сценарии
вызывают его.

Оно же объясняет, почему отмена не может «пройти мимо» возврата: счёт
блокируется, платёж остаётся в ``PENDING``, и единственный способ завершить
отмену — разблокировать счёт и повторить заход. Написать ``CANCELLED`` без денег
значило бы отдать клиенту платёж, за который он не получит сумму обратно.

Функция работает **внутри уже открытой транзакции** вызывающего: платёж, события и
движение денег обязаны зафиксироваться одним коммитом. Открывать и коммитить
транзакцию здесь нельзя — сценарий решает, когда она закрывается.
"""

from src.core_service.application.ports.unit_of_work import UnitOfWork
from src.core_service.domain.entities.payment import Payment
from src.core_service.domain.exceptions import EntityNotFoundError


async def release_hold(uow: UnitOfWork, payment: Payment) -> None:
    """Возвращает списанную под платёж сумму на счёт плательщика.

    Счёт читается под блокировкой строки (``get_for_update``): возврат меняет
    баланс, и две одновременные операции по счёту не должны потерять одну из них.

    :param uow: открытая транзакция, в которой лежат репозитории;
    :param payment: платёж, чей холд отпускается; платёж **не** сохраняется —
        вызывающий решает, когда коммитить;
    :raises EntityNotFoundError: счёт плательщика исчез из хранилища. Вернуть холд
        некуда, и это повод упасть, а не «списать в никуда».
    :raises AccountBlocked: счёт заблокирован. Деньги тогда останутся в холде, а
        платёж — в текущем статусе: это осознанно. «Пропустить» возврат и записать
        терминальный статус нельзя — клиент потеряет сумму, а починить холд потом
        будет некому. Освобождение счёта и повторный заход сценария сделают возврат
        позже; сценарий падает с доменной ошибкой, а не делает вид, что всё в порядке.
    """
    account = await uow.accounts.get_for_update(payment.from_account_id)
    if account is None:
        raise EntityNotFoundError(f'Счёт плательщика {payment.from_account_id} не найден для возврата средств')
    account.deposit(payment.amount)
    await uow.accounts.update(account)
