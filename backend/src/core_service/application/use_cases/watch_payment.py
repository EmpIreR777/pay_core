"""Сценарий потока статусов платежа (T-2.8).

Клиент, заплативший деньги, хочет видеть, чем всё закончилось, не опрашивая
сервер сам. Для этого есть поток: gRPC server-streaming (T-6.5) и SSE-эндпоинт
(T-7.5) строятся поверх этого генератора. Сценарий — асинхронный генератор:
он отдаёт кадры состояния платежа, пока есть что показывать.

Как устроен поток:

* **Каждый кадр — отдельное чтение через** :class:`GetPaymentUseCase` (T-2.5),
  а не переписанная копия его логики. Актуализация зависшего ``PROCESSING``,
  возврат холда при отказе провайдера и игнорирование промежуточных ответов
  уже написаны и проверены там; повторить их здесь — значит дать второй копии
  шанс забыть вернуть деньги. Композиция сценариев, а не наследование.
* **Транзакция не живёт между кадрами.** Пока потребитель разбирает кадр, в
  базе нет ни открытых транзакций, ни удерживаемых строк: держать соединение
  ради долгого стрима — верный способ занять базу чужой работой.
* **Кадр — это смена статуса.** Первый кадр всегда несёт текущее состояние
  (иначе клиент ждал бы первого изменения, не получив вообще ничего), дальше
  кадр уходит только при смене статуса: тот же статус с новой меткой времени —
  не новость, а шум на каждый тик.
* **Поток конечен.** Он закрывается, когда статус терминальный (исход известен,
  показывать больше нечего), либо по сроку :data:`WATCH_MAX_DURATION_SECONDS` —
  долгие ожидания решаются переподключением на транспорте, а не вечным
  генератором.
* **Пауза между чтениями приходит извне** (``sleeper``). ``asyncio.sleep``
  здесь не зовётся напрямую: тесты не имеют права зависеть от реального
  времени (AGENT.md §5: никаких flaky-тестов со ``sleep``).

Чего поток сам **не** делает: не меняет платеж и не рассылает события —
изменения приходят извне (вебхук T-2.7, отмена T-2.6, сверка T-2.10), а
актуализация происходит только как чтение T-2.5. Если между опросами статус
успел поменяться дважды, клиент получит последний: это опрос состояния, а не
подписка на события.
"""

from collections.abc import AsyncIterator, Awaitable, Callable
from datetime import timedelta
from typing import Final

from src.core_service.application.dto.payment import GetPaymentInput, GetPaymentOutput
from src.core_service.application.ports.clock import Clock
from src.core_service.application.use_cases.get_payment import GetPaymentUseCase

#: Пауза между чтениями состояния платежа. Секунда — компромисс между
#: отзывчивостью стрима и частотой опроса: провайдера спрашиваем только для
#: ``PROCESSING`` и только пока клиент фактически смотрит поток.
WATCH_POLL_INTERVAL_SECONDS: Final[float] = 1.0

#: Верхняя граница жизни одного потока. Поток — не подписка навсегда: по её
#: истечении генератор закрывается, клиент переподключается и снова получает
#: текущее состояние. Срок делает поток конечным по построению — иначе
#: брошенный генератор с неизменившимся платежом жил бы вечно.
WATCH_MAX_DURATION_SECONDS: Final[float] = 300.0


class WatchPaymentUseCase:
    """Поток статусов платежа: читает, пока статус меняется или живёт срок."""

    __slots__ = ('_clock', '_get_payment', '_sleeper')

    def __init__(
        self,
        *,
        get_payment: GetPaymentUseCase,
        clock: Clock,
        sleeper: Callable[[float], Awaitable[None]],
    ) -> None:
        """:param get_payment: сценарий чтения с актуализацией (T-2.5) — каждый
            кадр потока это его вызов;
        :param clock: часы: по ним строится срок жизни потока;
        :param sleeper: пауза между чтениями состояния. Внедряется вместо
            прямого ``asyncio.sleep``: в тестах время обязано идти по-другому,
            иначе проверка срока упирается в реальные секунды.
        """
        self._get_payment = get_payment
        self._clock = clock
        self._sleeper = sleeper

    async def execute(self, data: GetPaymentInput) -> AsyncIterator[GetPaymentOutput]:
        """Отдаёт состояние платежа до терминального статуса или срока потока.

        Метод — асинхронный генератор: тело не выполняется до первого чтения
        кадра, поэтому ошибка всплывает на первом кадре, а не в момент вызова.

        :param data: какой платёж смотрим — тот же вопрос, что и у чтения
            (T-2.5), поэтому и тот же DTO;
        :raises EntityNotFoundError: платежа нет (до первого кадра) либо он исчез
            посреди потока;
        :raises PaymentProviderError: провайдер недоступен в момент актуализации.
            Ошибка не замалчивается: клиент обязан увидеть, что состояние узнать
            не удалось, и переподключиться.
        """
        deadline = self._clock.now() + timedelta(seconds=WATCH_MAX_DURATION_SECONDS)

        # Первый кадр — текущее состояние, даже если оно уже терминальное:
        # клиент обязан получить ответ сразу, а не ждать первого изменения.
        current = await self._get_payment.execute(data)
        yield current
        last_status = current.status

        while not last_status.is_terminal:
            if self._clock.now() >= deadline:
                return
            await self._sleeper(WATCH_POLL_INTERVAL_SECONDS)
            current = await self._get_payment.execute(data)
            if current.status is last_status:
                # Статус не менялся: кадр с тем же содержимым — шум. Читаем
                # дальше, не расходуя ни очередь потребителя, ни его внимание.
                continue
            last_status = current.status
            yield current
