"""Единица работы на Postgres + async SQLAlchemy (T-3.5).

Адаптер порта :class:`UnitOfWork`: транзакционная граница, внутри которой
репозитории счетов и платежей пишут в **одну** сессию. Сага T-2.4 держит транзакцию
открытой через вызов провайдера и коммитит в два шага, поэтому граница обязана
принадлежать объекту, а не быть размазанной по репозиториям.

Решения, которые стоит проговорить:

* **Репозитории не коммитят (T-3.3, T-3.4), единица работы коммитит.** Отсюда
  следует всё остальное: если бы репозиторий фиксировал изменения сам, «списание
  холда + запись платежа» развалилось бы на две транзакции, и платёж без списания
  (или наоборот) стал бы обычным дефектом, а не аварийной остановкой.
* **Сессия принадлежит единице работы.** Она создаётся в ``__aenter__`` и
  закрывается в ``__aexit__`` — соединение возвращается в пул на границе
  транзакции, а не тогда, когда о нём вспомнит сборщик мусора. Движком, наоборот,
  владеет процесс: поднимать и закрывать пул на каждый сценарий нельзя, поэтому
  адаптер получает готовую фабрику сессий.
* **Одна единица работы — одна транзакция.** Повторный вход в открытую единицу
  отвергается: вложенный контекст закрыл бы внешнюю транзакцию, и сценарий
  продолжил бы писать в уже закрытую. Сага, которой нужны две транзакции, получает
  две единицы работы из фабрики ``Callable[[], UnitOfWork]`` (T-2.1).
* **Выход без исключения коммитит, с исключением — откатывает, и исключение
  уходит наружу.** Подавить его нельзя: сага обязана увидеть отказ, чтобы снять
  резервацию ключа идемпотентности (T-2.4, T-2.7). Откат обязателен и на отказе
  самой базы — иначе сессия осталась бы в «сломанном» состоянии, и следующая
  запись в ней падала бы без объяснения.
* **Сессия закрывается всегда, даже если ``commit`` упал.** Утечка соединения
  выглядит как постепенное замедление шлюза и заканчивается отказом в пуле, а не
  падением одного запроса, — и заметить её трудно.
* **Явный ``commit`` внутри контекста не мешает выходу.** Сценарий коммитит сам
  (это его решение), а ``__aexit__`` фиксирует уже пустую транзакцию: второй
  ``COMMIT`` в Postgres не уходит, лишних записей не появляется. Симметрично,
  ``rollback`` внутри контекста окончателен — коммит на выходе не воскресит
  откатанные изменения.
* **Репозитории вне контекста недоступны.** Сценарий, забывший ``async with``,
  падает здесь с внятной причиной, а не в ``AttributeError`` где-то в
  репозитории. Молчание было бы опаснее: запись ушла бы в базу мимо транзакции
  именно тогда, когда сценарий рассчитывал на её откат.
* **Транзакция открывается явно, в ``__aenter__``.** Так инвариант «внутри
  контекста открыта транзакция» верен с первой строки, а не «с момента первого
  запроса». Сам ``begin()`` базу не трогает — соединение берётся лениво, на
  первом SQL. Настройки сессии (``autoflush``, ``expire_on_commit``) задаёт
  фабрика: переопределять их здесь означало бы разойтись с процессом.
"""

from dataclasses import dataclass
from types import TracebackType
from typing import Self

from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from src.core_service.application.ports.account_repository import AccountRepository
from src.core_service.application.ports.payment_repository import PaymentRepository
from src.db.repositories.account import PostgresAccountRepository
from src.db.repositories.payment import PostgresPaymentRepository


@dataclass(frozen=True)
class _OpenTransaction:
    """Сессия и репозитории, привязанные к одной открытой транзакции.

    Отдельный объект, а не три поля единицы работы, — по одной причине: пустая
    транзакция и транзакция без репозиториев не должны быть возможны. Сессия и
    оба репозитория либо есть все, либо нет ни одного, и состояние «открыто»
    проверяется в одном месте, а не в каждом свойстве.
    """

    session: AsyncSession
    accounts: AccountRepository
    payments: PaymentRepository


class PostgresUnitOfWork:
    """Транзакционная граница сценариев над Postgres."""

    def __init__(self, session_maker: async_sessionmaker[AsyncSession]) -> None:
        """:param session_maker: фабрика сессий приложения. Единица работы не
        создаёт и не закрывает движок: его жизненный цикл принадлежит процессу,
        а сессия берётся на время одной транзакции.
        """
        self._session_maker = session_maker
        self._opened: _OpenTransaction | None = None

    @property
    def accounts(self) -> AccountRepository:
        """Репозиторий счетов текущей транзакции."""
        return self._require_opened().accounts

    @property
    def payments(self) -> PaymentRepository:
        """Репозиторий платежей текущей транзакции."""
        return self._require_opened().payments

    async def __aenter__(self) -> Self:
        """Открывает сессию и транзакцию, возвращает саму единицу работы."""
        if self._opened is not None:
            raise RuntimeError('Единица работы уже открыта: повторный вход закрыл бы текущую транзакцию')
        session = self._session_maker()
        await session.begin()
        self._opened = _OpenTransaction(
            session=session,
            accounts=PostgresAccountRepository(session),
            payments=PostgresPaymentRepository(session),
        )
        return self

    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        """Фиксирует или откатывает транзакцию и всегда возвращает сессию в пул.

        Отсутствие ``return`` здесь не опечатка: ``None`` означает «исключение не
        подавлено», и сценарий узнаёт о провале транзакции.
        """
        opened = self._require_opened()
        try:
            if exc_type is None:
                await opened.session.commit()
            else:
                await opened.session.rollback()
        finally:
            # Состояние снимается до закрытия сессии: упавший ``close()`` не должен
            # оставить единицу работы, которая выглядит открытой.
            self._opened = None
            await opened.session.close()

    async def commit(self) -> None:
        """Фиксация изменений по требованию сценария.

        Текст контракта намеренно не дублируется: он принадлежит порту
        ``UnitOfWork`` (T-2.1). Здесь важно другое — что это запись **сценария**, а
        не скрытый побочный эффект выхода из контекста: сага решает сама, на какой
        границе закрывать транзакцию.
        """
        await self._require_opened().session.commit()

    async def rollback(self) -> None:
        """Откат изменений по требованию сценария.

        Отличается от отката на выходе из контекста тем, что применяется в
        **середине** транзакции: сценарий может отказаться от шага, не выходя из
        контекста, и дальше работать с чистым состоянием.
        """
        await self._require_opened().session.rollback()

    def _require_opened(self) -> _OpenTransaction:
        """Открытая транзакция или отказ с внятной причиной."""
        opened = self._opened
        if opened is None:
            raise RuntimeError('Единица работы не открыта: репозитории доступны только внутри `async with`')
        return opened
