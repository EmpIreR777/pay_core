"""Фоновая уборка просроченных ключей идемпотентности (T-4.4).

Ответ, сохранённый под ключом, обещан клиенту ровно на срок жизни записи. Срок
вышел — обещание исполнено, и строка стала занимать место в таблице без
причины. Ключи копятся только от клиентских повторов, поэтому таблица растёт
медленно, но неуклонно, и без уборки она перестанет помещаться в память Postgres
рано или поздно. Уборку запускает шедулер раз в час.

Решения, которые стоит проговорить, — каждое из них меняет поведение при отказе:

* **Граница отсечения — ``<=``, а не ``<`` из плана задачи.** Читающий адаптер
  (T-4.2) отдаёт запись только при ``expires_at > now()``, то есть считает
  мёртвой запись с ``expires_at <= now()``. Уборка обязана отсекать ровно то
  же множество: при ``<`` запись, которую хранилище уже отказывается отдавать
  на повтор, осталась бы лежать в таблице навсегда — не страшно, но это запись,
  о которой никто не знает и которую никто не уберёт. Два места должны
  называть «просрочено» одним и тем же условием, иначе они разойдутся при
  первой же правке одного из них.
* **Срок задаёт вызывающий, а не база.** Срок записи пишет адаптер T-4.2 по часам
  сценария, и именно по ним хранилище решает, что запись ещё жива. Отсекать по
  серверному времени нельзя: расхождение часов машины и базы удалило бы запись,
  которую приложение ещё считает обещанной клиенту, и повтор с тем же ключом не
  нашёл бы ответа — выполнил бы операцию заново. Для шлюза это вторая оплата по
  одному ключу, то есть ровно то, ради чего весь эпик и затевался. Поэтому
  момент отсечки передаётся аргументом, и «кто просрочен» решают одни часы.
* **Порциями, а не одним ``DELETE`` на всю таблицу.** Удаление всех просроченных
  строк за одну транзакцию держит блокировки до самого конца и раздувает
  журнал: уборка, зависшая на большой таблице, мешала бы живым записям. Каждая
  порция — отдельная транзакция, поэтому упавшая уборка начинается заново и не
  оставляет за собой полузакрытых хвостов.
* **Отсечка вычисляется один раз, до цикла.** Если брать время на каждой
  порции, множество «просроченных» едет вместе с часами, уборка становится
  величиной, зависящей от собственной длительности, и на большой таблице может
  не завершиться вовсе. Замороженная отсечка делает проход конечным и
  повторяемым: всё, что протухло к моменту старта, убирается за этот проход, а
  протухшее после — дождётся следующего часа.
* **Redis уборке не подлежит.** Ответ в кэше живёт ровно столько, сколько
  осталось до ``expires_at`` записи (T-4.2), и Redis сам убирает его по TTL.
  Синхронная уборка кэша была бы второй реализацией того же срока — источником
  правды, который однажды разойдётся с первым.
"""

from datetime import datetime
from typing import Any, Final, cast

from sqlalchemy import delete, select
from sqlalchemy.engine import CursorResult
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker
from sqlalchemy.sql import Delete

from src.db.models.idempotency_key import IdempotencyKeyModel

#: Сколько просроченных записей убирать за одну транзакцию. Порция ограничивает
#: время блокировки и объём журнала, а не задаёт темп уборки: проход удалит все
#: просроченные строки, просто несколькими короткими транзакциями.
CLEANUP_BATCH_SIZE: Final[int] = 1_000


async def delete_expired_idempotency_keys(
    session_maker: async_sessionmaker[AsyncSession],
    cutoff: datetime,
    *,
    batch_size: int = CLEANUP_BATCH_SIZE,
) -> int:
    """Удалить из ``idempotency_keys`` все записи, чей срок вышел.

    :param session_maker: фабрика сессий приложения — движком и пулом владеет
        процесс, уборка их не создаёт;
    :param cutoff: момент, записи с ``expires_at`` на который и раньше уходят.
        Время передаёт вызывающий, а не берётся здесь: писатель записи (T-4.2)
        считает срок по часам сценария, и уборка обязана считать по тем же
        часам, иначе расхождение между машиной и базой решило бы судьбу записи
        по-разному с двух сторон;
    :param batch_size: сколько строк удалять за одну транзакцию;
    :returns: сколько записей удалено за весь проход.

    Отсечка фиксируется в аргументе и потому не меняется, пока идёт проход:
    время двигается вместе с множеством «просроченных», и на большой таблице
    проход завис бы, всё время догоняя собственный хвост.

    Возвращаемое число — не украшение: по нему видно, что уборка вообще
    работает. Ноль на протяжении часов означает, что задача падает тихо, и
    таблица растёт незаметно, пока упрётся в диск.
    """
    deleted_total = 0
    while True:
        async with session_maker() as session:
            result = await session.execute(_batch_statement(cutoff, batch_size))
            await session.commit()
        # ``execute`` на DELETE отдаёт ``Result``, у которого ``rowcount`` есть
        # только у ``CursorResult``: число удалённых строк. Приводим явно.
        # Само значение тоже проверяем: драйвер сообщает ``-1``, когда строки
        # не считал, и без проверки минус сложился бы в итог (уборка вернула бы
        # отрицательное число), а ``-1 < batch_size`` вышел бы из цикла — то
        # есть проход объявил бы себя завершённым, ничего не удалив.
        deleted_in_batch = cast('CursorResult[Any]', result).rowcount
        if deleted_in_batch < 0:
            return deleted_total
        deleted_total += deleted_in_batch
        # Порция короче запрошенной — просроченных строк больше нет: цикл
        # выходит. Проверка именно такая, а не «удалилось ноль»: последняя
        # неполная порция и есть признак конца, а полная порция обязана быть
        # обработана в любом случае.
        if deleted_in_batch < batch_size:
            return deleted_total


def _batch_statement(cutoff: datetime, batch_size: int) -> Delete:
    """Запрос одной порции уборки: не больше ``batch_size`` самых старых строк.

    Отбор кандидатов идёт подзапросом с ``ORDER BY expires_at LIMIT``, а не
    одним ``DELETE`` по условию. Разница — в том, сколько строк база держит
    заблокированными за раз: подзапрос ограничивает порцию заранее, ещё до
    удаления, и упирается в индекс по сроку, который и был построен под уборку
    (T-4.1). Порядок по сроку заодно убирает самые старые записи первыми — чем
    реже их видели повторы, тем меньше от них пользы.
    """
    expired_keys = (
        select(IdempotencyKeyModel.key)
        .where(IdempotencyKeyModel.expires_at <= cutoff)
        .order_by(IdempotencyKeyModel.expires_at)
        .limit(batch_size)
    )
    return delete(IdempotencyKeyModel).where(IdempotencyKeyModel.key.in_(expired_keys))
