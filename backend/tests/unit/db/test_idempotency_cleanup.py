"""Юнит-тесты SQL уборки просроченных ключей идемпотентности (T-4.4).

Уборка лежит в слое ``db`` рядом с хранилищем, с которым делит таблицу и
соглашение о сроке, поэтому и тестируется здесь, а не рядом с задачей, которая
её запускает: место проверки должно совпадать с местом кода, иначе проверка
сама станет «законом» отдельно от того, что проверяет.

Живая Postgres доказывает то, чего из SQL не видно, — что база действительно
убирает строки и делает это порциями
(``tests/integration/test_idempotency_cleanup.py``), регистрация задачи
проверяется отдельно (``tests/unit/tasks/``).
"""

from datetime import UTC, datetime

from sqlalchemy.dialects import postgresql

from src.db.idempotency_cleanup import CLEANUP_BATCH_SIZE, _batch_statement

#: Фиксированное «сейчас»: граница отсечения проверяется точно, и результат
#: не должен зависеть от того, как быстро выполняется тест.
NOW = datetime(2026, 3, 14, 15, 9, 26, tzinfo=UTC)


def _sql(*, cutoff: datetime = NOW, batch_size: int = 100) -> str:
    """Текст SQL одной порции уборки, приведённый к виду, читаемому глазами."""
    statement = _batch_statement(cutoff, batch_size)
    compiled = statement.compile(dialect=postgresql.dialect(), compile_kwargs={'literal_binds': True})
    return ' '.join(str(compiled).split())


# --- Граница отсечения --------------------------------------------------------


def test_cleanup_cuts_records_expired_at_the_boundary() -> None:
    """Убирается запись с ``expires_at``, равным отсечке, — знак ``<=``, не ``<``.

    Читающий адаптер (T-4.2) отдаёт запись только при ``expires_at > now()``:
    запись с ``expires_at == now()`` он уже считает мёртвой и на повтор не
    отдаёт. Уборка обязана отсекать ровно то же множество, иначе такая запись
    не удалялась бы никогда — а её и нельзя было бы удалить вручную, не зная
    правила. Строгий ``<`` из плана задачи оставил бы её в таблице навсегда.

    Проверяется текстом SQL, а не «запись исчезла»: подмена знака — правка
    одного символа, и поймать её должен именно этот тест.
    """
    sql = _sql(cutoff=NOW)

    assert 'idempotency_keys.expires_at <= ' in sql
    assert 'idempotency_keys.expires_at < ' not in sql


def test_cleanup_does_not_depend_on_created_at() -> None:
    """Отсекает по сроку, а не по времени появления строки.

    Запись может пролежать в базе сутки и быть вовсе не просроченной, если её
    срок длинный. Уборка по ``created_at`` снесла бы живые ответы, и повтор с
    тем же ключом пошёл бы выполняться заново — то есть клиент получил бы
    второй платёж вместо своего. ``created_at`` в запросе уборки не участвует.
    """
    assert 'created_at' not in _sql()


def test_cleanup_uses_server_time_free_cutoff() -> None:
    """Отсечка приходит аргументом, а не ``now()`` сервера.

    Срок записи пишет адаптер T-4.2 по часам приложения, и по ним же
    хранилище решает, что запись жива. Отсечение по серверному времени при
    расхождении часов машины и базы удалило бы запись, которую приложение ещё
    считает обещанной клиенту: повтор не нашёл бы ответа и создал бы второй
    платёж. Проверяется отсутствием ``now()`` в SQL — значение отсечки
    подставляется параметром, а не считается базой.
    """
    assert 'now()' not in _sql()


# --- Порция -------------------------------------------------------------------


def test_batch_is_limited_in_one_statement() -> None:
    """Одна порция удаляет не больше заданного числа строк.

    Без ``LIMIT`` уборка брала бы всю таблицу одной транзакцией: блокировки
    держались бы до конца прохода, а упавшая уборка откатывала бы всю работу
    разом. Порция обязана быть видна в самом запросе — иначе ограничение
    существовало бы только в Python, а база получила бы команду без него.
    """
    assert 'LIMIT 100' in _sql(batch_size=100)


def test_batch_orders_by_expiry_to_reap_the_oldest_first() -> None:
    """Порция берёт самые старые записи — те, которыми повторяли реже всех.

    Порядок по сроку заодно ведёт уборку по индексу, построенному под неё
    (T-4.1). Без порядка база выбирала бы кандидатов как придётся и могла бы
    годами держать в хвосте одну и ту же запись.
    """
    assert 'ORDER BY idempotency_keys.expires_at' in _sql()


def test_default_batch_size_is_a_positive_integer() -> None:
    """Размер порции по умолчанию — положительное число.

    Ноль или отрицательное значение означали бы бесконечный цикл: порция не
    удалила бы ничего и не «завершила» бы проход. Константа публична, и её
    значение вправе задавать, поэтому его форма проверяется.
    """
    assert isinstance(CLEANUP_BATCH_SIZE, int)
    assert CLEANUP_BATCH_SIZE > 0
